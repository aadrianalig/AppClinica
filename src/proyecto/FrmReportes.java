    private void cargarEnTabla(String[] columnas, Object[][] datos) {
        configurarTablaVacia();
        for (String c : columnas) {
            modelo.addColumn(c);
        }
        if (datos != null) {
            for (Object[] fila : datos) {
                modelo.addRow(fila);
            }
        }
    }

