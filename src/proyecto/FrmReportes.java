    private void btnIngresosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresosActionPerformed
        if (gg == null) {
            JOptionPane.showMessageDialog(this, "No hay referencia a GestorDeGestores");
            return;
        }
        GestorFacturacion gf = gg.getGestorFacturacion();
        if (gf == null) {
            JOptionPane.showMessageDialog(this, "No hay gestor de facturacion");
            return;
        }

        // columnas
        String[] cols = {"Id", "PacienteDoc", "Consulta", "Servicios", "Total", "Pago"};
        configurarTablaVacia();
        for (String c : cols) {
            modelo.addColumn(c);
        }

        Factura[] arr = gf.getFacturas();
        int n = gf.getCantidad();

        double sumaConsulta = 0.0;
        double sumaServicios = 0.0;
        double sumaTotal = 0.0;

        for (int i = 0; i < n; i++) {
            Factura f = arr[i];
            Object[] fila = new Object[]{
                f.getId(),
                f.getPaciente().getDocumento(), // o nombres si prefieres
                f.getMontoConsulta(),
                f.getMontoServicios(),
                f.getTotal(),
                f.getMetodoPago()
            };
            modelo.addRow(fila);

            // acumular
            sumaConsulta = sumaConsulta + f.getMontoConsulta();
            sumaServicios = sumaServicios + f.getMontoServicios();
            sumaTotal = sumaTotal + f.getTotal();
        }

        // fila en blanco + totales
        modelo.addRow(new Object[]{"", "", "", "", "", ""});
        modelo.addRow(new Object[]{"Totales", "", sumaConsulta, sumaServicios, sumaTotal, ""});

        lblTitulo.setText("Ingresos");
        lblResumen.setText("Registros: " + n + "  |  Total ingresos: " + sumaTotal);
    }//GEN-LAST:event_btnIngresosActionPerformed

    private void btnEmpleadosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEmpleadosActionPerformed
        if (gestorReportes == null) {
            JOptionPane.showMessageDialog(this, "No hay referencia a GestorReportes");
            return;
        }
        String[] cols = gestorReportes.columnasEmpleados();
        Object[][] data = gestorReportes.datosEmpleados();
        cargarEnTabla(cols, data);
        lblTitulo.setText("Empleados");

        // resumen por rol
        int[] conteo = gestorReportes.conteoEmpleadosPorRol();
        String[] roles = gestorReportes.rolesBase();

        // fila en blanco + encabezado de resumen (simple)
        modelo.addRow(new Object[]{"", "", "", "", ""});
        modelo.addRow(new Object[]{"Resumen por rol", "", "", "", ""});
        for (int i = 0; i < roles.length; i++) {
            modelo.addRow(new Object[]{roles[i], conteo[i], "", "", ""});
        }

        lblResumen.setText("Total empleados: " + data.length);
    }//GEN-LAST:event_btnEmpleadosActionPerformed

