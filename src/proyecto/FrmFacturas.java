    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String id = txtId.getText().trim();
        String docPaciente = txtPacienteDoc.getText().trim();
        String sConsulta = txtMontoConsulta.getText().trim();
        String sServicios = txtMontoServicios.getText().trim();
        String metodo = cbMetodoPago.getSelectedItem().toString();

        if (id.equals("") || docPaciente.equals("") || sConsulta.equals("") || sServicios.equals("")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete Id, Paciente, Consulta y Servicios");
            return;
        }

        // 1) buscar paciente
        modelo.Paciente pac = gg.getGestorPacientes().buscarPorDocumento(docPaciente);
        if (pac == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Paciente no existe");
            return;
        }

        // 2) parsear montos
        double mConsulta, mServicios;
        try {
            mConsulta = Double.parseDouble(sConsulta);
            mServicios = Double.parseDouble(sServicios);
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Montos inválidos");
            return;
        }

        // 3) construir factura (tu constructor calcula total)
        modelo.Factura f = new modelo.Factura(id, pac, mConsulta, mServicios, metodo);

        // 4) registrar
        boolean ok = gestorFacturacion.registrarFactura(f);
        if (!ok) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo registrar (duplicado o sin espacio)");
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this, "Factura registrada");
        limpiarCampos();
        cargarTabla();
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String id = txtId.getText().trim();
        if (id.equals("")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese Id");
            return;
        }
        modelo.Factura f = gestorFacturacion.buscarPorId(id);
        if (f == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Factura no encontrada");
        } else {
            // mostramos documento del paciente (o nombres, como prefieras)
            txtPacienteDoc.setText(f.getPaciente().getDocumento());
            txtMontoConsulta.setText(String.valueOf(f.getMontoConsulta()));
            txtMontoServicios.setText(String.valueOf(f.getMontoServicios()));
            cbMetodoPago.setSelectedItem(f.getMetodoPago());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

