    private void configurarTabla() {
        modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int r, int c) {
                return false;
            }
        };
        modelo.addColumn("Id");
        modelo.addColumn("PacienteDoc");
        modelo.addColumn("Consulta");
        modelo.addColumn("Servicios");
        modelo.addColumn("Total");
        modelo.addColumn("Pago");
        tblFacturas.setModel(modelo);
    }

    private void limpiarTabla() {
        while (modelo.getRowCount() > 0) {
            modelo.removeRow(0);
        }
    }

    private void limpiarCampos() {
        txtId.setText("");
        txtMontoServicios.setText("");
        txtMontoConsulta.setText("");
        txtMontoServicios.setText("");
        cbMetodoPago.setSelectedIndex(0);
        txtId.requestFocus();
    }

    private void cargarTabla() {
        limpiarTabla();
        Factura[] arr = gestorFacturacion.getFacturas();
        int cant = gestorFacturacion.getCantidad();
        for (int i = 0; i < cant; i++) {
            Factura f = arr[i];
            // Ajusta getters segun tu modelo Factura:
            modelo.addRow(new Object[]{
                f.getId(),
                f.getPaciente().getDocumento(),
                f.getMontoConsulta(),
                f.getMontoServicios(),
                f.getTotal(),
                f.getMetodoPago()
            });
        }
    }

